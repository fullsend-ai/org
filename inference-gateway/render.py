#!/usr/bin/env python3
"""Render inference-gateway/config.yaml from config.tmpl.yaml, allowlist.yaml and gateway.env.

render.py                write config.yaml
render.py --verify-ids   also check every allowlist entry against the GitHub API (needs gh)
render.py --check        write nothing; exit 1 if config.yaml is not the rendered output
render.py --print-env    print the validated gateway.env as shell assignments (for deploy.sh)
"""

import argparse
import json
import re
import subprocess
import sys
from pathlib import Path

import yaml

HERE = Path(__file__).resolve().parent
ENV_KEYS = ("P", "PNUM", "R", "N", "AUD", "VERSION", "DIGEST", "RPM", "TPM", "MAX_INSTANCES")
INT_KEYS = ("PNUM", "RPM", "TPM", "MAX_INSTANCES")
# deploy.sh and the lint workflow eval the --print-env output: keep this to shell-inert characters.
SAFE_VALUE = re.compile(r"^[A-Za-z0-9._:/-]+$")
REPO_NAME = re.compile(r"^[A-Za-z0-9-]+/[A-Za-z0-9._-]+$")
MARKER = re.compile(r"__([A-Z]+)__")
HEADER = (
    "# GENERATED by render.py from config.tmpl.yaml, allowlist.yaml and gateway.env. Do not edit.\n"
)
GITHUB_ISSUER = "https://token.actions.githubusercontent.com"
# The caller identity every allow rule tests; must match config.tmpl.yaml.
CALLER = (
    '(default(jwt.repository, "") + "@" + default(jwt.repository_id, "")'
    ' + "@" + default(jwt.repository_owner_id, ""))'
)
# Errors any caller (CLI or scripts/lint.py) reports as a message, not a traceback.
INPUT_ERRORS = (ValueError, KeyError, TypeError, AttributeError, OSError, yaml.YAMLError)


def load_env() -> dict:
    """Plain KEY=VALUE lines; no quoting, no inline comments, no shell, no duplicates."""
    env = {}
    for n, line in enumerate((HERE / "gateway.env").read_text().splitlines(), 1):
        line = line.strip()
        if not line or line.startswith("#"):
            continue
        key, sep, value = line.partition("=")
        if not sep or key not in ENV_KEYS or not SAFE_VALUE.match(value):
            raise ValueError(
                f"gateway.env:{n}: expected KEY=VALUE with KEY in {ENV_KEYS} and a plain value"
            )
        if key in env:
            raise ValueError(f"gateway.env:{n}: duplicate {key}")
        env[key] = value
    missing = [k for k in ENV_KEYS if k not in env]
    if missing:
        raise ValueError(f"gateway.env: missing {missing}")
    for k in INT_KEYS:
        if not env[k].isdigit() or int(env[k]) < 1:
            raise ValueError(f"gateway.env: {k} must be a positive integer")
    if not re.fullmatch(r"[0-9a-f]{64}", env["DIGEST"]):
        raise ValueError("gateway.env: DIGEST must be a sha256 hex digest")
    return env


def load_allowlist() -> list:
    doc = yaml.safe_load((HERE / "allowlist.yaml").read_text())
    repos = doc.get("repos") if isinstance(doc, dict) else None
    if not isinstance(repos, list) or not repos:
        raise ValueError("allowlist.yaml: expected a non-empty 'repos' list")
    names, ids = set(), set()
    for r in repos:
        if not isinstance(r, dict) or set(r) != {"name", "id", "owner_id"}:
            raise ValueError(f"allowlist.yaml: each entry needs exactly name, id, owner_id: {r!r}")
        if not isinstance(r["name"], str) or not REPO_NAME.match(r["name"]):
            raise ValueError(f"allowlist.yaml: {r['name']!r} is not an owner/name repository")
        for k in ("id", "owner_id"):
            if not (isinstance(r[k], str) and r[k].isdigit()):
                raise ValueError(f"allowlist.yaml: {r['name']}: {k} must be a quoted digit string")
        if r["name"] in names or r["id"] in ids:
            raise ValueError(f"allowlist.yaml: duplicate entry for {r['name']} / id {r['id']}")
        names.add(r["name"])
        ids.add(r["id"])
    return repos


def allow_list() -> str:
    """The rendered CEL list every model's allow rule must test against."""
    items = (json.dumps(f"{r['name']}@{r['id']}@{r['owner_id']}") for r in load_allowlist())
    return "[" + ", ".join(items) + "]"


def render() -> str:
    env = load_env()
    values = {"AUD": env["AUD"], "ALLOW": allow_list(), "RPM": env["RPM"], "TPM": env["TPM"]}

    def fill(m: re.Match) -> str:
        if m.group(1) not in values:
            raise ValueError(f"config.tmpl.yaml: unknown marker {m.group(0)}")
        return values[m.group(1)]

    return HEADER + MARKER.sub(fill, (HERE / "config.tmpl.yaml").read_text())


def check_config(text: str) -> list:
    """Errors in a rendered config. Lint is the only reviewer of the template, so the security
    shape is pinned exactly: only the known sections, strict jwtAuth trusting GitHub's issuer and
    JWKS for AUD, rate-limit keys and allow rules that are exactly the allowlist test, and rules
    that are single-key mappings (agentgateway treats a bare string rule as allow, and no allow
    rule at all as allow-all)."""
    try:
        cfg = yaml.safe_load(text)
    except yaml.YAMLError as e:
        return [f"config.yaml: invalid YAML: {e}"]
    try:
        allow = allow_list()
        aud = load_env()["AUD"]
    except INPUT_ERRORS as e:
        return [str(e)]
    canonical = f"{CALLER} in {allow}"
    bucket_key = f'({canonical}) ? "fleet" : "other"'
    jwt_auth = {
        "mode": "strict",
        "providers": [
            {
                "issuer": GITHUB_ISSUER,
                "audiences": [aud],
                "jwks": {"url": f"{GITHUB_ISSUER}/.well-known/jwks"},
            }
        ],
    }
    if not isinstance(cfg, dict) or set(cfg) != {"config", "gateways", "llm"}:
        return ["config.yaml: top level must be exactly config, gateways, llm"]
    llm = cfg["llm"]
    if not isinstance(llm, dict) or set(llm) != {"gateways", "discovery", "policies", "models"}:
        return ["config.yaml: llm must be exactly gateways, discovery, policies, models"]
    errors = []
    policies = llm["policies"] if isinstance(llm["policies"], dict) else {}
    if set(policies) != {"jwtAuth", "localRateLimit"}:
        errors.append("config.yaml: llm.policies must be exactly jwtAuth, localRateLimit")
    if policies.get("jwtAuth") != jwt_auth:
        errors.append(
            f"config.yaml: llm.policies.jwtAuth must be strict GitHub OIDC ({GITHUB_ISSUER},"
            f" its JWKS, audiences [{aud}])"
        )
    limits = policies.get("localRateLimit")
    if not isinstance(limits, list) or not limits:
        errors.append("config.yaml: llm.policies.localRateLimit must be a non-empty list")
    elif any(not isinstance(rl, dict) or rl.get("key") != bucket_key for rl in limits):
        errors.append(
            "config.yaml: every localRateLimit key must be the allowlist fleet/other split"
        )
    models = llm["models"]
    if not isinstance(models, list) or not models:
        return [*errors, "config.yaml: llm.models must be a non-empty list"]
    for m in models:
        name = m.get("name") if isinstance(m, dict) else m
        auth = m.get("authorization") if isinstance(m, dict) else None
        rules = auth.get("rules") if isinstance(auth, dict) else None
        if not isinstance(rules, list) or not all(
            isinstance(r, dict) and len(r) == 1 and next(iter(r)) in ("allow", "deny", "require")
            for r in rules
        ):
            errors.append(
                f"config.yaml: model {name!r} rules must be single-key allow/deny/require"
            )
            continue
        allows = [r["allow"] for r in rules if "allow" in r]
        if not allows or any(a != canonical for a in allows):
            errors.append(
                f"config.yaml: model {name!r} allow rules must be exactly the allowlist test"
            )
    return errors


def verify_ids() -> None:
    bad = 0
    for r in load_allowlist():
        try:
            out = subprocess.run(
                [
                    "gh",
                    "api",
                    f"repos/{r['name']}",
                    "--jq",
                    "{full_name, id: (.id|tostring), owner_id: (.owner.id|tostring)}",
                ],
                check=True,
                capture_output=True,
                text=True,
            ).stdout
        except (subprocess.CalledProcessError, FileNotFoundError) as e:
            sys.exit(f"--verify-ids: gh api repos/{r['name']} failed: {e}")
        got = json.loads(out)
        want = {"full_name": r["name"], "id": r["id"], "owner_id": r["owner_id"]}
        if got != want:
            print(f"MISMATCH {r['name']}: allowlist {want} != GitHub {got}")
            bad += 1
    if bad:
        sys.exit(1)
    print("all allowlist ids match GitHub")


def main(argv: list) -> None:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawTextHelpFormatter)
    ap.add_argument("--check", action="store_true")
    ap.add_argument("--verify-ids", action="store_true")
    ap.add_argument("--print-env", action="store_true")
    args = ap.parse_args(argv)
    try:
        if args.print_env:
            for k, v in load_env().items():
                print(f"{k}={v}")
            return
        if args.verify_ids:
            verify_ids()
        text = render()
    except INPUT_ERRORS as e:
        sys.exit(str(e))
    errors = check_config(text)
    if errors:
        sys.exit("\n".join(errors))
    target = HERE / "config.yaml"
    if args.check:
        if not target.exists() or target.read_text() != text:
            sys.exit(
                "inference-gateway/config.yaml is stale: run python3 inference-gateway/render.py"
            )
        return
    target.write_text(text)
    print(f"wrote {target.relative_to(HERE.parent)}")


if __name__ == "__main__":
    main(sys.argv[1:])
